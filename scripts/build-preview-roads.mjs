#!/usr/bin/env node
// Generates src/campuses/alangilan.preview.roads.ts — the UNVERIFIED PROTOTYPE PREVIEW of the five Alangilan
// road geometries — from the committed diagnostic run. Developer-only. Run with:  npm run routes:preview
//
// No network request is made. The script:
//   1. requires the diagnostic GeoJSON to be tracked, committed and unmodified, with the expected SHA-256;
//   2. rebuilds each route's OSRM response from the stored raw data and re-runs the generator's own analysis
//      (verifyDiagnosticRoute), requiring every stored value to equal the recomputed one;
//   3. writes only the application paths, their geometry hashes and provenance — no raw GeoJSON, OSRM
//      responses or server URLs.
// The output is not approval data: formal reviewed geometry stays in src/campuses/alangilan.roads.ts.
import { execFileSync } from 'node:child_process'
import { readFileSync, renameSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { haversineM } from '../src/lib/geo.js'
import { CAMPUS, CORRIDORS, geojsonSha256, parseStrictJson } from '../src/lib/routeChecks.js'
import { STATUS, statusOf, verifyDiagnosticRoute } from './build-routes.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const PREVIEW_SOURCE = Object.freeze({
  runId: '20261117T124418Z-45d1ea',
  sha256: '70df8461a670d3113524b524fcde322c030cf542d22202177fc5d51c1f86156e',
})
export const sourcePath = (runId) => `docs/routes/diagnostics/alangilan-candidates.DIAGNOSTIC.${runId}.geojson`
export const TARGET = 'src/campuses/alangilan.preview.roads.ts'
export const PREVIEW_STATUS = 'unverified-prototype-preview'
const r1 = (n) => Math.round(n * 10) / 10

// Pure: exact diagnostic bytes in, preview data out. Throws on any mismatch; nothing is defaulted.
export function buildPreviewRoads(bytes, { expected = PREVIEW_SOURCE, corridors = CORRIDORS, campus = CAMPUS } = {}) {
  const sha = geojsonSha256(bytes)
  if (sha !== expected.sha256) throw new Error(`diagnostic SHA-256 ${sha} does not match the expected ${expected.sha256}`)
  const geo = parseStrictJson(new TextDecoder('utf-8', { fatal: true }).decode(bytes))
  if (geo?.biyahe?.runId !== expected.runId) throw new Error(`diagnostic run ${geo?.biyahe?.runId} is not ${expected.runId}`)
  const routes = corridors.map((c) => {
    const { result: r, problems } = verifyDiagnosticRoute(geo, c)
    if (!r || problems.length) throw new Error(`${c.id}: the diagnostic does not reproduce: ${problems.join('; ')}`)
    if (statusOf(r) === STATUS.failed) throw new Error(`${c.id}: FAILED routes cannot be previewed`)
    return {
      routeId: c.id,
      path: r.appPath,
      routeGeometrySha256: r.routeGeometrySha256,
      pathEnds: c.pathEnds ?? null,
      warnings: r.warnings.map((w) => ({ code: w.code, value: typeof w.value === 'number' ? w.value : null })),
      endpointSeparationM: r1(haversineM(c.end, r.snappedEnd)),
      endRoad: r.endSnapRoad,
    }
  })
  return {
    status: PREVIEW_STATUS, campus: 'alangilan', campusAnchor: [campus[0], campus[1]],
    runId: expected.runId, sourceGeojsonSha256: sha, versions: geo.biyahe.versions, routes,
  }
}

// Deterministic TypeScript text; each [lat, lng] pair on one line.
export function renderPreviewModule(data) {
  const json = JSON.stringify(data, null, 2).replace(/\[\n\s+(-?[\d.]+),\n\s+(-?[\d.]+)\n\s+\]/g, '[$1, $2]')
  return [
    '// GENERATED by scripts/build-preview-roads.mjs (npm run routes:preview). Do not edit by hand.',
    '//',
    `// UNVERIFIED PROTOTYPE PREVIEW of the five Alangilan corridors, from diagnostic run ${data.runId}.`,
    '// Candidate road geometry only: not formally approved and not physically verified. Shown only in the',
    '// development server or an explicit route-preview build (see src/lib/previewGeometry.ts). Formal reviewed',
    '// geometry lives in ./alangilan.roads.ts and always takes precedence.',
    "import type { PreviewRoadSet } from '../lib/previewGeometry'",
    '',
    `export const ALANGILAN_PREVIEW_ROADS: PreviewRoadSet = ${json}`,
    '',
  ].join('\n')
}

function main() {
  if (process.env.npm_lifecycle_event !== 'routes:preview') {
    console.error('Run with: npm run routes:preview')
    process.exit(1)
  }
  const rel = sourcePath(PREVIEW_SOURCE.runId)
  const git = (...args) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim()
  if (!git('ls-files', '--', rel)) throw new Error(`${rel} is not tracked`)
  if (git('--no-optional-locks', 'status', '--porcelain', '--', rel)) throw new Error(`${rel} has uncommitted changes`)
  const bytes = new Uint8Array(readFileSync(join(ROOT, rel)))
  const committed = new Uint8Array(execFileSync('git', ['cat-file', 'blob', `HEAD:${rel}`], { cwd: ROOT, encoding: 'buffer' }))
  if (geojsonSha256(committed) !== geojsonSha256(bytes)) throw new Error(`${rel}: working bytes differ from the committed blob`)
  const text = renderPreviewModule(buildPreviewRoads(bytes))
  const target = join(ROOT, TARGET)
  writeFileSync(`${target}.tmp`, text)
  renameSync(`${target}.tmp`, target)
  console.log(`Wrote ${TARGET} from run ${PREVIEW_SOURCE.runId} (SHA-256 ${PREVIEW_SOURCE.sha256}). Unverified prototype preview; not approval data.`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main()
